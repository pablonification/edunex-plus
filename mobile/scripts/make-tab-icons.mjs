// Draws the bottom tabs' icons as Android vector drawables (mobile/assets/tab-icons/*.xml) from Microsoft's Fluent UI
// System Icons (MIT), the family the app draws everywhere else (src/ui/icons.tsx): each in the form Fluent drew for
// 24 px, the size the bar shows it at, regular for a tab at rest and filled for the tab picked (Material's rule:
// filled when active). Android draws them natively, at once, at any density; the bar tints them.
// plugins/tab-icons.js copies them into the app's resources at prebuild. Run again after changing a glyph:
//
//   node mobile/scripts/make-tab-icons.mjs
import fs from "node:fs";
import path from "node:path";
import { fluent } from "./fluent.mjs";

const MOBILE = path.resolve(import.meta.dirname, "..");
const OUT = path.join(MOBILE, "assets", "tab-icons");

/**
 * Drawable name (tab_<name>) → Fluent icon. Five shapes told apart at a squint: a house, a calendar of days, a
 * clipboard with its ticks, the graduation cap (kuliah, the courses), a person (Profil, where Akademik now lives).
 */
export const TAB_ICONS = {
  home: "home",
  schedule: "calendar-ltr",
  tasks: "clipboard-task-list-ltr",
  courses: "hat-graduation",
  profile: "person",
};

const drawable = (glyph, form) =>
  [
    `<?xml version="1.0" encoding="utf-8"?>`,
    `<!-- Generated by mobile/scripts/make-tab-icons.mjs from Fluent UI System Icons (MIT): ${glyph}, 24 px, ${form.toLowerCase()}. -->`,
    `<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">`,
    ...fluent(glyph, 24, form).map(
      ({ d, evenOdd }) => `  <path android:fillColor="#FF000000"${evenOdd ? ` android:fillType="evenOdd"` : ""} android:pathData="${d}" />`,
    ),
    `</vector>`,
    "",
  ].join("\n");

fs.mkdirSync(OUT, { recursive: true });
// Only this script's drawables live here: clear the old ones, so a tab that's gone leaves no drawable behind.
for (const file of fs.readdirSync(OUT)) if (/^tab_.*\.xml$/.test(file)) fs.rmSync(path.join(OUT, file));
for (const [name, glyph] of Object.entries(TAB_ICONS)) {
  fs.writeFileSync(path.join(OUT, `tab_${name}.xml`), drawable(glyph, "Regular"));
  fs.writeFileSync(path.join(OUT, `tab_${name}_filled.xml`), drawable(glyph, "Filled"));
}
console.log(`Wrote ${Object.keys(TAB_ICONS).length * 2} drawables to ${path.relative(process.cwd(), OUT)}`);
