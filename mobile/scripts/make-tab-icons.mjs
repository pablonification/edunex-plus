// Draws the bottom tabs' icons as Android vector drawables (mobile/assets/tab-icons/*.xml) from the
// same Phosphor glyphs the app draws everywhere else (src/ui/icons.tsx): the regular weight for a tab
// at rest, the filled one for the tab picked (Material's rule: filled when active). Android draws
// them natively, at once, at any density; the bar tints them. plugins/tab-icons.js copies them into
// the app's resources at prebuild. Run again after changing a glyph:
//
//   node mobile/scripts/make-tab-icons.mjs
import fs from "node:fs";
import path from "node:path";

const MOBILE = path.resolve(import.meta.dirname, "..");
const DEFS = path.join(MOBILE, "node_modules", "phosphor-react-native", "src", "defs");
const OUT = path.join(MOBILE, "assets", "tab-icons");

/** Drawable name (tab_<name>) → Phosphor glyph. */
export const TAB_ICONS = {
  home: "House",
  schedule: "CalendarDots",
  tasks: "ListChecks",
  courses: "BookOpen",
  academic: "GraduationCap",
};

/** The `d` of each <Path> of one weight in a Phosphor definition file. */
function paths(source, weight) {
  const start = source.indexOf(`'${weight}',`);
  if (start < 0) throw new Error(`no ${weight} weight`);
  const end = source.indexOf("\n  ],", start);
  return [...source.slice(start, end).matchAll(/<Path\s+d="([^"]+)"/g)].map((m) => m[1]);
}

const drawable = (ds) =>
  [
    `<?xml version="1.0" encoding="utf-8"?>`,
    `<!-- Generated by mobile/scripts/make-tab-icons.mjs from Phosphor (MIT). -->`,
    `<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="256" android:viewportHeight="256">`,
    ...ds.map((d) => `  <path android:fillColor="#FF000000" android:pathData="${d}" />`),
    `</vector>`,
    "",
  ].join("\n");

fs.mkdirSync(OUT, { recursive: true });
for (const [name, glyph] of Object.entries(TAB_ICONS)) {
  const source = fs.readFileSync(path.join(DEFS, `${glyph}.tsx`), "utf8");
  fs.writeFileSync(path.join(OUT, `tab_${name}.xml`), drawable(paths(source, "regular")));
  fs.writeFileSync(path.join(OUT, `tab_${name}_filled.xml`), drawable(paths(source, "fill")));
}
console.log(`Wrote ${Object.keys(TAB_ICONS).length * 2} drawables to ${path.relative(process.cwd(), OUT)}`);
