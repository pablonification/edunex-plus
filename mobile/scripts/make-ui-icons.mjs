// Writes the phone's in-app icons (src/ui/fluent/<name>.ts) from Microsoft's Fluent UI System Icons (MIT), the family the
// desktop draws (src/app/ui/icons.tsx): each icon's path data as plain strings, regular and filled, at every size
// Fluent drew it between 12 and 48 px, so src/ui/icons.tsx draws the form made for the size it shows at with
// react-native-svg. Never @fluentui/react-icons' components on the phone: they're DOM.
//
// The icons are the ones src/ui/icons.tsx imports (`from "./fluent/<name>"`), so the app carries only those: add an
// import there, then run
//
//   node mobile/scripts/make-ui-icons.mjs
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fluent, sizesOf } from "./fluent.mjs";

const UI = path.resolve(import.meta.dirname, "..", "src", "ui");
const OUT = path.join(UI, "fluent");
const SIZES = [12, 16, 20, 24, 28, 32, 48];

/** One drawing as one `d`. Fluent draws nearly all as one path; the few in parts (none evenodd) join into one. */
function one(name, size, form) {
  const parts = fluent(name, size, form);
  if (parts.some((p) => p.evenOdd)) throw new Error(`${name} ${size} ${form} fills evenodd: draw it in parts`);
  return parts.map((p) => p.d).join("");
}

const source = fs.readFileSync(path.join(UI, "icons.tsx"), "utf8");
const names = [...new Set([...source.matchAll(/from "\.\/fluent\/([a-z0-9-]+)"/g)].map((m) => m[1]))].sort();
if (names.length === 0) throw new Error("src/ui/icons.tsx imports no ./fluent/<name>");

fs.mkdirSync(OUT, { recursive: true });
for (const file of fs.readdirSync(OUT)) if (file.endsWith(".ts") && !names.includes(file.slice(0, -3))) fs.rmSync(path.join(OUT, file));
let bytes = 0;
for (const name of names) {
  const sizes = sizesOf(name).filter((s) => SIZES.includes(s));
  if (sizes.length === 0) throw new Error(`Fluent draws no ${name} between 12 and 48 px`);
  const rows = sizes.map((s) => `  [${s}, ${JSON.stringify(one(name, s, "Regular"))}, ${JSON.stringify(one(name, s, "Filled"))}],`);
  const text = [
    `// Generated by mobile/scripts/make-ui-icons.mjs from Fluent UI System Icons (MIT): ${name}. Don't edit; run the script.`,
    `// Each row: the size Fluent drew it for (its viewBox), then the regular and the filled form's path.`,
    `const drawn: readonly (readonly [size: number, regular: string, filled: string])[] = [`,
    ...rows,
    `];`,
    `export default drawn;`,
    "",
  ].join("\n");
  bytes += text.length;
  fs.writeFileSync(path.join(OUT, `${name}.ts`), text);
}
// As the repository's formatter writes them, so running this again changes nothing.
execFileSync("npx", ["biome", "format", "--write", OUT], { cwd: path.resolve(UI, "..", "..", ".."), stdio: "ignore" });
console.log(`Wrote ${names.length} icons (${Math.round(bytes / 1024)} KB) to ${path.relative(process.cwd(), OUT)}`);
